import { promises as fs } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { printSchema } from "graphql";
import codegenConfig from "../codegen.ts";
import { buildGeneratedSchema } from "../schemas-src/graphql/build-schema.ts";
import { repoRoot } from "./lib.ts";
import type { OpenApiParameters } from "../schemas-src/graphql/query-arguments.ts";

// Use one native require-resolved graph for type generation. This also keeps
// GraphQL class identities shared when callers use a transformed ESM loader.
// The declaration builder and its ESM printer above exchange only SDL text
// with this graph; their GraphQLSchema instance never crosses that boundary.
const requireForCodegen = createRequire(import.meta.url);
const { codegen } = requireForCodegen("@graphql-codegen/core") as typeof import("@graphql-codegen/core");
const { getCachedDocumentNodeFromSchema } = requireForCodegen("@graphql-codegen/plugin-helpers") as typeof import("@graphql-codegen/plugin-helpers");
const typescriptPlugin = requireForCodegen("@graphql-codegen/typescript") as typeof import("@graphql-codegen/typescript");
const typescriptResolversPlugin = requireForCodegen("@graphql-codegen/typescript-resolvers") as typeof import("@graphql-codegen/typescript-resolvers");
const { gqlPluckFromCodeString } = requireForCodegen("@graphql-tools/graphql-tag-pluck") as typeof import("@graphql-tools/graphql-tag-pluck");
const { buildASTSchema, lexicographicSortSchema, parse, Source } = requireForCodegen("graphql") as typeof import("graphql");

// Runs the supported @graphql-codegen/core API with explicit plugins against
// the fixed local SDL module (types-epic D, #7862). Loading a single code string
// directly keeps config discovery, glob expansion and remote loaders out of
// this pipeline. Build and drift validation share this exact output function.
//
// ## The SDL is the first output (#10214)
//
// Until #10214 the schema codegen read was `src/graphql-sdl.ts` -- 6,582
// hand-written lines, the last surface not built from the shared Zod contract.
// Everything it contained is declared in `schemas-src/graphql/` (the
// build-schema.ts header lists the six sources), so the SDL is emitted here
// from `buildGeneratedSchema()` and codegen runs against the emitted module.
//
// ONE step, not two, deliberately: codegen READS the schema module, so a
// separate build step would demand an ordering both of scripts/build.ts's step
// lists have to state and can state differently. Emitting first inside the
// same function makes the order a fact of the code. It also means the drift
// gate covers both artifacts by iterating one outputs array -- a stale
// schema.ts fails the same check a stale types.ts always has.
//
// ## Why the runtime gets a printed STRING and not the GraphQLSchema
//
// `buildGeneratedSchema()` costs ~1s of module-scope work (Zod -> JSON Schema
// -> GraphQL type construction); Workers enforce a startup-CPU limit of
// ~400ms, and the api Worker's init already spends most of it. Printing at
// build time leaves the runtime doing what it always did -- `buildSchema(SDL)`,
// ~16ms -- and keeps the resolver model unchanged: an SDL-built schema carries
// no resolver map, which src/graphql.ts relies on (rootValue via the default
// field resolver, with `subscribe` and the two nested-list resolvers attached
// by hand after the fact).
//
// `printSchema` and never string concatenation: the printer owns SDL syntax
// (escaping, block strings, field order), and a generator that assembled
// source text would be a second, worse printer.

/** Where the emitted SDL module lands, repo-relative. */
export const GRAPHQL_SCHEMA_PATH = codegenConfig.schema;

const GRAPHQL_TYPES_PATH = "generated/graphql/types.ts";

const OPENAPI_PATH = "public/metagraph/openapi.json";

/**
 * The template-literal escapes, applied in this order (backslash first, or the
 * escapes just added would themselves be escaped). Ten descriptions carry a
 * backtick today (Zod `.describe()` prose like "Distinct from `generated_at`"),
 * so emitting raw would truncate the literal at the first one. The COOKED
 * value -- what the runtime and every gate that imports `SDL` sees -- is
 * byte-identical to the printed SDL. Codegen's raw pluck behavior is preserved
 * separately; it does not fully cook template escapes.
 */
function asTemplateLiteral(sdl: string): string {
  return sdl
    .replaceAll("\\", "\\\\")
    .replaceAll("`", "\\`")
    .replaceAll("${", "\\${");
}

async function generateGraphqlSchemaModule(): Promise<{
  filename: string;
  content: string;
}> {
  const openapi = JSON.parse(
    await fs.readFile(path.join(repoRoot, OPENAPI_PATH), "utf8"),
  ) as OpenApiParameters;
  const { schema } = buildGeneratedSchema(openapi);
  const sdl = printSchema(schema);
  const content = `// GENERATED by scripts/generate-graphql-types.ts -- do not edit (#10214).
//
// The published GraphQL SDL, printed from the schema
// schemas-src/graphql/build-schema.ts assembles out of the Zod components,
// the published-name declarations, QUERY_BINDINGS and the route-derived
// arguments. It replaced src/graphql-sdl.ts, which was the same surface
// maintained by hand.
//
// Regenerate with \`npm run build:graphql-types\`;
// \`validate:graphql-types-drift\` fails CI if the committed copy and a fresh
// build disagree.
//
// The \`/* GraphQL */\` magic comment before the template literal is
// @graphql-tools/graphql-tag-pluck's documented way to extract SDL from a
// plain (non-\`gql\`-tagged) template literal -- codegen.ts's schema pointer
// relies on it. It is a comment, not a tag function, so it changes nothing
// about how this module executes.
export const SDL = /* GraphQL */ \`
${asTemplateLiteral(sdl)}\`;
`;
  return { filename: GRAPHQL_SCHEMA_PATH, content };
}

/**
 * Read only GraphQL text from the fixed module. The same pure pluck API used
 * by Codegen's code-file loader preserves its existing raw escape behavior
 * without executing the module. A missing/invalid SDL cannot fall back to
 * importing source code. This is not a template-cooking correctness change.
 */
async function generateGraphqlTypeOutput(
  schemaModuleContent: string,
): Promise<{ filename: string; content: string }> {
  const sources = await gqlPluckFromCodeString(
    path.join(repoRoot, GRAPHQL_SCHEMA_PATH),
    schemaModuleContent,
  );
  if (sources.length !== 1) {
    throw new Error(
      `Expected exactly one GraphQL SDL in ${GRAPHQL_SCHEMA_PATH}; found ${sources.length}.`,
    );
  }

  // Preserve the plucked source's text, name and location as data. Parsing,
  // sorting, Core and the plugins all use the same native GraphQL graph.
  const plucked = sources[0];
  const source = new Source(plucked.body, plucked.name, plucked.locationOffset);
  // CLI's loader uses sort:true. Supplying the sorted schemaAst keeps Core
  // from rebuilding its type map and changing canonical resolver-map order.
  const schemaAst = lexicographicSortSchema(
    buildASTSchema(parse(source), { assumeValidSDL: true }),
  );
  const outputConfig = codegenConfig.generates[GRAPHQL_TYPES_PATH];
  const content = await codegen({
    filename: GRAPHQL_TYPES_PATH,
    schema: getCachedDocumentNodeFromSchema(schemaAst),
    schemaAst,
    documents: [],
    plugins: outputConfig.plugins.map((plugin) => ({ [plugin]: {} })),
    pluginMap: {
      typescript: typescriptPlugin,
      "typescript-resolvers": typescriptResolversPlugin,
    },
    config: {
      ...outputConfig.config,
      emitLegacyCommonJSImports: true,
      importExtension: "",
    },
    emitLegacyCommonJSImports: true,
    importExtension: "",
  });
  return { filename: GRAPHQL_TYPES_PATH, content };
}

async function readSchemaModule(): Promise<string> {
  return fs.readFile(path.join(repoRoot, GRAPHQL_SCHEMA_PATH), "utf8");
}

export async function generateGraphqlTypes(
  // Kept for existing callers; Core itself emits no progress output.
  _options: { silent?: boolean } = {},
): Promise<{ filename: string; content: string }[]> {
  const schemaModule = await generateGraphqlSchemaModule();
  const typeOutput = await generateGraphqlTypeOutput(
    await readSchemaModule(),
  );
  return [schemaModule, typeOutput];
}

export async function buildGraphqlTypes(): Promise<void> {
  // Write the fresh schema before reading the fixed module for type output.
  // Drift validation deliberately reads the committed schema without writes.
  const schemaModule = await generateGraphqlSchemaModule();
  const target = path.join(repoRoot, schemaModule.filename);
  await fs.mkdir(path.dirname(target), { recursive: true });
  await fs.writeFile(target, schemaModule.content, "utf8");
  const output = await generateGraphqlTypeOutput(
    await readSchemaModule(),
  );
  await fs.mkdir(path.dirname(path.join(repoRoot, output.filename)), {
    recursive: true,
  });
  await fs.writeFile(path.join(repoRoot, output.filename), output.content, "utf8");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  await buildGraphqlTypes();
  console.log("Generated GraphQL schema module and resolver/argument types.");
}
