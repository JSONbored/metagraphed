import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { DatabaseSync } from "node:sqlite";
import { pathToFileURL } from "node:url";
import { D1_EXPORT_COLUMNS } from "../src/d1-export-columns.ts";
import { D1_EXPORT_TABLES } from "../src/d1-export-tables.ts";
import { SQLITE_DOCUMENT_DECODER } from "../src/sqlite-document-decoder.ts";

/** Derive schema information offline; the native server never creates SQLite tables. */
export function exportProjectionSource(): string {
  const raw = readFileSync(
    new URL("../generated/db/d1-schema.json", import.meta.url),
    "utf8",
  );
  const definitions = JSON.parse(raw) as {
    type: string;
    name: string;
    sql: string;
  }[];
  const db = new DatabaseSync(":memory:", { allowExtension: false });
  try {
    const identity = db
      .prepare(
        "SELECT sqlite_version() AS version,sqlite_source_id() AS sourceId",
      )
      .get();
    if (
      identity?.version !== SQLITE_DOCUMENT_DECODER.version ||
      identity.sourceId !== SQLITE_DOCUMENT_DECODER.sourceId
    )
      throw new Error("Export projection requires the pinned SQLite decoder");
    for (const kind of ["table", "view"])
      for (const definition of definitions.filter(
        (entry) => entry.type === kind,
      ))
        db.exec(definition.sql);
    const tables = Object.fromEntries(
      Object.keys(D1_EXPORT_TABLES).map((table) => {
        const allowed = new Set(D1_EXPORT_COLUMNS[table]!.split(" "));
        const columns = db.prepare(`PRAGMA table_info("${table}")`).all() as {
          name: string;
          type: string;
          notnull: number;
          pk: number;
        }[];
        if (
          !columns.length ||
          columns.some(
            (column) =>
              !column.name.startsWith("_") && !allowed.has(column.name),
          )
        )
          throw new Error(`Unapproved export projection: ${table}`);
        const approved = columns.filter((column) => allowed.has(column.name));
        const legacyNominators =
          table === "nominator_positions" &&
          JSON.stringify(approved.map((column) => column.name)) ===
            JSON.stringify([...allowed].slice(0, -2));
        if (approved.length !== allowed.size && !legacyNominators)
          throw new Error(`Incomplete export projection: ${table}`);
        return [
          table,
          approved.map(({ name, type, notnull, pk }) => [
            name,
            type,
            notnull,
            pk,
          ]),
        ];
      }),
    );
    const data = {
      format: "metagraphed-export-projection/v1",
      sourceSha256: createHash("sha256").update(raw).digest("hex"),
      tables,
    };
    return (
      "// Generated by scripts/generate-export-projection.ts; do not edit.\n// prettier-ignore\n" +
      `export const EXPORT_PROJECTION = ${JSON.stringify(data, null, 2)} as const;\n`
    );
  } finally {
    db.close();
  }
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  const target = new URL(
    "../generated/db/export-projection.ts",
    import.meta.url,
  );
  const expected = exportProjectionSource();
  if (process.argv.includes("--check")) {
    if (readFileSync(target, "utf8") !== expected)
      throw new Error(
        "Export projection is stale; run scripts/generate-export-projection.ts",
      );
  } else {
    writeFileSync(target, expected);
  }
}
