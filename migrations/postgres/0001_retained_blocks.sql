-- Load-phase PostgreSQL schema for migrations/retained-blocks/0001_retained_blocks.sql.
-- The seven physical tables preserve source IDs, ordinals and nullable payloads.
-- The original schema has no foreign keys or triggers on these tables.
CREATE SCHEMA retained;

CREATE TABLE retained.history_block_sources (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  identity text COLLATE "C" NOT NULL UNIQUE,
  network bigint NOT NULL CHECK (network IN (0, 1)),
  source text COLLATE "C" NOT NULL,
  expected_rows bigint NOT NULL CHECK (expected_rows >= 0),
  received_rows bigint NOT NULL DEFAULT 0
    CHECK (received_rows >= 0 AND received_rows <= expected_rows),
  active bigint NOT NULL DEFAULT 0 CHECK (active IN (0, 1))
);

CREATE TABLE retained.history_block_authors (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  address text COLLATE "C" NOT NULL UNIQUE
);

CREATE TABLE retained.history_blocks (
  network bigint NOT NULL CHECK (network IN (0, 1)),
  source_id bigint NOT NULL,
  ordinal bigint NOT NULL CHECK (ordinal >= 0),
  block_number bigint,
  block_hash text COLLATE "C",
  parent_hash text COLLATE "C",
  author_id bigint,
  extrinsic_count bigint,
  event_count bigint,
  spec_version bigint,
  observed_at bigint,
  PRIMARY KEY (source_id, ordinal)
);

CREATE INDEX history_blocks_order
  ON retained.history_blocks (network, observed_at DESC, block_number DESC);
CREATE INDEX history_blocks_author
  ON retained.history_blocks (network, author_id, observed_at DESC, block_number DESC);
CREATE INDEX history_blocks_spec
  ON retained.history_blocks (network, spec_version, observed_at DESC, block_number DESC);
CREATE INDEX history_blocks_author_spec
  ON retained.history_blocks (network, author_id, spec_version, observed_at DESC, block_number DESC);
CREATE INDEX history_blocks_extrinsics
  ON retained.history_blocks (network, extrinsic_count, observed_at DESC, block_number DESC);
CREATE INDEX history_blocks_events
  ON retained.history_blocks (network, event_count, observed_at DESC, block_number DESC);
CREATE INDEX history_blocks_height
  ON retained.history_blocks (network, block_number, observed_at DESC);

CREATE TABLE retained.history_block_chunks (
  source_id bigint NOT NULL,
  start_row bigint NOT NULL,
  rows bigint NOT NULL CHECK (rows > 0),
  digest text COLLATE "C" NOT NULL,
  PRIMARY KEY (source_id, start_row)
);

CREATE TABLE retained.history_block_source_counts (
  source_id bigint NOT NULL,
  kind text COLLATE "C" NOT NULL CHECK (kind IN ('events', 'extrinsics')),
  value bigint NOT NULL,
  rows bigint NOT NULL CHECK (rows > 0),
  PRIMARY KEY (source_id, kind, value)
);

CREATE TABLE retained.history_block_counts (
  network bigint NOT NULL CHECK (network IN (0, 1)),
  kind text COLLATE "C" NOT NULL CHECK (kind IN ('events', 'extrinsics')),
  value bigint NOT NULL,
  rows bigint NOT NULL CHECK (rows > 0),
  PRIMARY KEY (network, kind, value)
);

CREATE TABLE retained.history_block_state (
  network bigint PRIMARY KEY CHECK (network IN (0, 1)),
  generation text COLLATE "C" NOT NULL,
  table_uuid text COLLATE "C" NOT NULL,
  snapshot text COLLATE "C" NOT NULL,
  sequence bigint NOT NULL,
  generated_at bigint NOT NULL,
  source_rows bigint NOT NULL,
  source_files bigint NOT NULL,
  coverage text COLLATE "C"
);

CREATE VIEW retained.history_block_rows AS
SELECT b.network, b.block_number, b.block_hash, b.parent_hash, a.address AS author,
       b.extrinsic_count, b.event_count, b.spec_version, b.observed_at
FROM retained.history_blocks b
JOIN retained.history_block_sources s
  ON s.id = b.source_id AND s.network = b.network AND s.active = 1
LEFT JOIN retained.history_block_authors a ON a.id = b.author_id;
