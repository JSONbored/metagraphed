-- Load phase for the non-triggered subnet and economic-history tables.
-- Boolean source fields use the qualified boolean01 codec. JSON stays text.
CREATE SCHEMA IF NOT EXISTS app;

CREATE TABLE app.subnet_hyperparams (
    netuid bigint PRIMARY KEY,
    kappa_ratio double precision,
    immunity_period bigint,
    min_allowed_weights bigint,
    max_weight_limit_ratio double precision,
    tempo bigint,
    weights_version text,
    weights_rate_limit double precision,
    activity_cutoff bigint,
    activity_cutoff_factor bigint,
    registration_allowed boolean,
    target_regs_per_interval bigint,
    min_burn_tao double precision,
    max_burn_tao double precision,
    burn_half_life bigint,
    burn_increase_mult double precision,
    bonds_moving_avg_raw text,
    max_regs_per_block bigint,
    serving_rate_limit bigint,
    max_validators bigint,
    commit_reveal_period bigint,
    commit_reveal_enabled boolean,
    alpha_high_ratio double precision,
    alpha_low_ratio double precision,
    liquid_alpha_enabled boolean,
    alpha_sigmoid_steepness double precision,
    yuma_version bigint,
    subnet_is_active boolean,
    transfers_enabled boolean,
    bonds_reset_enabled boolean,
    user_liquidity_enabled boolean,
    owner_cut_enabled boolean,
    owner_cut_auto_lock_enabled boolean,
    min_childkey_take_ratio double precision,
    block_number bigint,
    captured_at bigint NOT NULL
);
CREATE TABLE app.subnet_hyperparams_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    netuid bigint NOT NULL,
    block_number bigint,
    observed_at bigint NOT NULL,
    kappa_ratio double precision,
    immunity_period bigint,
    min_allowed_weights bigint,
    max_weight_limit_ratio double precision,
    tempo bigint,
    weights_version text,
    weights_rate_limit double precision,
    activity_cutoff bigint,
    activity_cutoff_factor bigint,
    registration_allowed boolean,
    target_regs_per_interval bigint,
    min_burn_tao double precision,
    max_burn_tao double precision,
    burn_half_life bigint,
    burn_increase_mult double precision,
    bonds_moving_avg_raw text,
    max_regs_per_block bigint,
    serving_rate_limit bigint,
    max_validators bigint,
    commit_reveal_period bigint,
    commit_reveal_enabled boolean,
    alpha_high_ratio double precision,
    alpha_low_ratio double precision,
    liquid_alpha_enabled boolean,
    alpha_sigmoid_steepness double precision,
    yuma_version bigint,
    subnet_is_active boolean,
    transfers_enabled boolean,
    bonds_reset_enabled boolean,
    user_liquidity_enabled boolean,
    owner_cut_enabled boolean,
    owner_cut_auto_lock_enabled boolean,
    min_childkey_take_ratio double precision,
    hyperparams_hash text NOT NULL,
    UNIQUE (netuid, observed_at)
);
CREATE TABLE app.subnet_identity (
    netuid bigint PRIMARY KEY,
    block_number bigint NOT NULL,
    captured_at bigint NOT NULL,
    subnet_name text,
    symbol text,
    description text,
    github_repo text,
    subnet_url text,
    discord text,
    logo_url text,
    identity_hash text
);
CREATE TABLE app.subnet_identity_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    netuid bigint NOT NULL,
    block_number bigint NOT NULL,
    observed_at bigint NOT NULL,
    subnet_name text,
    symbol text,
    description text,
    github_repo text,
    subnet_url text,
    discord text,
    logo_url text,
    identity_hash text COLLATE "C" NOT NULL
);
CREATE TABLE app.subnet_ownership (
    netuid bigint PRIMARY KEY,
    owner_hotkey text COLLATE "C" NOT NULL,
    owner_coldkey text COLLATE "C" NOT NULL,
    captured_at bigint NOT NULL
);
CREATE TABLE app.subnet_ownership_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    netuid bigint NOT NULL,
    owner_hotkey text COLLATE "C" NOT NULL,
    owner_coldkey text COLLATE "C" NOT NULL,
    captured_at bigint NOT NULL
);
CREATE TABLE app.subnet_lifecycle (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    netuid bigint NOT NULL,
    event text NOT NULL CHECK (event IN ('registered', 'deregistered')),
    block_number bigint,
    observed_at bigint NOT NULL CHECK (observed_at >= 1000000000000),
    predates_capture boolean NOT NULL DEFAULT false,
    _invalidated_at bigint,
    _invalidation_reason text
);
CREATE TABLE app.subnet_burn_history (
    netuid bigint NOT NULL,
    observed_at bigint NOT NULL,
    burn_tao double precision NOT NULL,
    PRIMARY KEY (netuid, observed_at)
);
CREATE TABLE app.subnet_deregistration_daily (
    netuid bigint NOT NULL,
    snapshot_date text COLLATE "C" NOT NULL,
    moving_price double precision,
    registered_at_block bigint,
    subnet_mechanism bigint,
    network_immunity_period bigint,
    pinned_block bigint,
    captured_at bigint NOT NULL CHECK (captured_at >= 1000000000000),
    PRIMARY KEY (netuid, snapshot_date)
);
CREATE TABLE app.subnet_emission_enabled_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    netuid bigint NOT NULL,
    enabled boolean NOT NULL,
    previous_enabled boolean,
    block_number bigint,
    observed_at bigint NOT NULL,
    predates_capture boolean NOT NULL DEFAULT false
);
CREATE TABLE app.chain_concentration_daily (
    day text COLLATE "C" PRIMARY KEY,
    neuron_count bigint NOT NULL,
    card text NOT NULL,
    source_captured_at bigint,
    computed_at bigint NOT NULL,
    builder_version bigint NOT NULL
);
CREATE TABLE app.treasury_readings (
    netuid bigint NOT NULL,
    source_url text COLLATE "C" NOT NULL,
    read_at_sha text NOT NULL,
    observed_at bigint NOT NULL CHECK (observed_at >= 1000000000000),
    first_seen bigint NOT NULL CHECK (first_seen >= 1000000000000),
    found boolean NOT NULL,
    declared_share double precision CHECK (declared_share IS NULL OR declared_share BETWEEN 0 AND 1),
    treasury_address text,
    applies_to text,
    evidence_path text,
    review_state text NOT NULL DEFAULT 'candidate' CHECK (review_state IN ('candidate', 'reviewed', 'rejected')),
    reviewed_at bigint,
    PRIMARY KEY (netuid, source_url),
    CHECK (NOT found OR declared_share IS NOT NULL OR treasury_address IS NOT NULL),
    CHECK (found OR (declared_share IS NULL AND treasury_address IS NULL))
);
CREATE TABLE app.compute_declarations (
    netuid bigint NOT NULL,
    source_url text COLLATE "C" NOT NULL,
    read_at_sha text NOT NULL,
    observed_at bigint NOT NULL CHECK (observed_at >= 1000000000000),
    first_seen bigint NOT NULL CHECK (first_seen >= 1000000000000),
    found boolean NOT NULL,
    spec_version text,
    miner text CHECK (miner IS NULL OR json_typeof(miner::json) = 'object'),
    validator text CHECK (validator IS NULL OR json_typeof(validator::json) = 'object'),
    unscoped text CHECK (unscoped IS NULL OR json_typeof(unscoped::json) = 'object'),
    PRIMARY KEY (netuid, source_url),
    CHECK (NOT found OR miner IS NOT NULL OR validator IS NOT NULL OR unscoped IS NOT NULL),
    CHECK (found OR (miner IS NULL AND validator IS NULL AND unscoped IS NULL))
);
CREATE TABLE app.tao_usd_index (
    block_number bigint NOT NULL,
    observed_at bigint NOT NULL,
    usd_per_tao double precision,
    price_basis text NOT NULL CHECK (price_basis IN ('wrapped_onchain_median', 'insufficient_pools')),
    eth_usd double precision,
    pool_count bigint NOT NULL CHECK (pool_count >= 0),
    pools text NOT NULL DEFAULT '[]',
    PRIMARY KEY (block_number, observed_at),
    CHECK ((price_basis = 'insufficient_pools' AND usd_per_tao IS NULL)
        OR (price_basis <> 'insufficient_pools' AND usd_per_tao IS NOT NULL))
);
CREATE TABLE app.revenue_observations (
    surface_id text COLLATE "C" NOT NULL,
    netuid bigint NOT NULL,
    period text COLLATE "C" NOT NULL,
    grain text NOT NULL,
    amount double precision NOT NULL,
    currency text NOT NULL,
    provenance text NOT NULL CHECK (provenance IN ('probe-derived', 'chain-verified')),
    response_hash text NOT NULL,
    observed_at bigint NOT NULL CHECK (observed_at >= 1000000000000),
    PRIMARY KEY (surface_id, period)
);
CREATE TABLE app.revenue_probe_failures (
    surface_id text COLLATE "C" NOT NULL,
    netuid bigint NOT NULL,
    reason text NOT NULL,
    observed_at bigint NOT NULL CHECK (observed_at >= 1000000000000),
    PRIMARY KEY (surface_id, observed_at)
);
CREATE TABLE app.emission_flow_watch (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item text COLLATE "C" NOT NULL CHECK (item IN ('net_tao_flow_enabled', 'flow_norm_exponent',
        'tao_flow_cutoff', 'flow_ema_smoothing_factor', 'subnet_ema_tao_flow')),
    netuid bigint,
    is_set boolean NOT NULL,
    ema_block bigint,
    block_number bigint,
    observed_at bigint NOT NULL,
    predates_capture boolean NOT NULL DEFAULT false,
    CHECK ((item = 'subnet_ema_tao_flow' AND netuid IS NOT NULL AND ema_block IS NOT NULL)
        OR (item <> 'subnet_ema_tao_flow' AND netuid IS NULL AND ema_block IS NULL))
);
CREATE TABLE app.emission_gate_param_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    param text COLLATE "C" NOT NULL,
    value double precision,
    previous_value double precision,
    source text NOT NULL CHECK (source IN ('governance', 'runtime_recomputed')),
    block_number bigint,
    observed_at bigint NOT NULL,
    predates_capture boolean NOT NULL DEFAULT false
);
CREATE TABLE app.attribution_candidates (
    netuid bigint NOT NULL,
    ss58 text COLLATE "C" NOT NULL,
    source_url text COLLATE "C" NOT NULL,
    first_seen bigint NOT NULL CHECK (first_seen >= 1000000000000),
    last_seen bigint NOT NULL CHECK (last_seen >= 1000000000000),
    PRIMARY KEY (netuid, ss58, source_url)
);
CREATE TABLE app.attribution_sweeps (
    netuid bigint PRIMARY KEY,
    swept_at bigint NOT NULL CHECK (swept_at >= 1000000000000),
    sources_checked bigint NOT NULL,
    sources_read bigint NOT NULL,
    candidates bigint NOT NULL,
    verdict text NOT NULL CHECK (verdict IN ('none-published', 'candidates-found', 'unreachable', 'no-sources', 'listings-only')),
    CHECK (sources_checked >= 0 AND sources_read >= 0 AND sources_read <= sources_checked AND candidates >= 0)
);

