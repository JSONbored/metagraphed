-- Load phase. Preserve account, usage and alert state before enabling references.
-- Source 0/1 fields use the qualified boolean01 codec.
CREATE SCHEMA IF NOT EXISTS app;

CREATE TABLE app.rpc_accounts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ss58 text COLLATE "C" NOT NULL UNIQUE,
    tier text NOT NULL DEFAULT 'free',
    created_at bigint NOT NULL,
    last_login_at bigint
);
CREATE TABLE app.github_accounts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    github_user_id bigint NOT NULL UNIQUE,
    github_login text NOT NULL,
    tier text NOT NULL DEFAULT 'free',
    created_at bigint NOT NULL,
    last_login_at bigint
);
CREATE TABLE app.api_keys (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prefix text COLLATE "C" UNIQUE,
    secret_hash text,
    owner_contact text NOT NULL,
    tier text NOT NULL DEFAULT 'keyed',
    created_at bigint NOT NULL,
    revoked_at bigint,
    last_used_at bigint,
    account_id bigint,
    unkey_key_id text COLLATE "C",
    revocation_requested_at bigint
);
CREATE TABLE app.api_key_blocks (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id bigint NOT NULL,
    reason_code text NOT NULL,
    note text,
    blocked_at bigint NOT NULL,
    blocked_by text,
    unblocked_at bigint,
    unblocked_note text,
    account_kind text COLLATE "C" NOT NULL DEFAULT 'rpc' CHECK (account_kind IN ('rpc', 'github'))
);
CREATE TABLE app.api_key_usage_daily (
    account_id bigint NOT NULL,
    day text COLLATE "C" NOT NULL,
    route text COLLATE "C" NOT NULL,
    request_count bigint NOT NULL DEFAULT 0,
    rejected_count bigint NOT NULL DEFAULT 0,
    account_kind text COLLATE "C" NOT NULL DEFAULT 'rpc' CHECK (account_kind IN ('rpc', 'github')),
    PRIMARY KEY (account_kind, account_id, day, route)
);
CREATE TABLE app.api_quota_daily (
    -- D1's INTEGER affinity also accepts wide and fractional REAL values.
    -- Import exact source numbers before native-only auth migrations run.
    account_id numeric NOT NULL,
    day text COLLATE "C" NOT NULL,
    units_spent numeric NOT NULL DEFAULT 0,
    updated_at bigint NOT NULL,
    account_kind text COLLATE "C" NOT NULL DEFAULT 'rpc' CHECK (account_kind IN ('rpc', 'github')),
    PRIMARY KEY (account_kind, account_id, day)
);
CREATE TABLE app.api_usage_rollup (
    day text COLLATE "C" NOT NULL,
    route_family text COLLATE "C" NOT NULL,
    cost_shape text COLLATE "C" NOT NULL,
    request_count bigint NOT NULL DEFAULT 0,
    keyed_count bigint NOT NULL DEFAULT 0,
    PRIMARY KEY (day, route_family, cost_shape)
);
CREATE TABLE app.api_usage_rollup_batches (
    batch_id text COLLATE "C" PRIMARY KEY,
    sha256 text NOT NULL CHECK (length(sha256) = 64),
    expires_at bigint NOT NULL,
    applied boolean NOT NULL DEFAULT false
);
CREATE TABLE app.chain_alert_triggers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_token text NOT NULL,
    name text,
    table_filter text,
    netuid bigint,
    event_kind text,
    account text,
    min_amount_tao double precision,
    channel text NOT NULL CHECK (channel IN ('webhook', 'email', 'telegram', 'discord', 'webpush')),
    destination text NOT NULL,
    active boolean NOT NULL DEFAULT true,
    created_at bigint NOT NULL,
    updated_at bigint NOT NULL,
    last_matched_at bigint,
    match_count bigint NOT NULL DEFAULT 0,
    condition text,
    owner_ss58 text COLLATE "C"
);
CREATE TABLE app.chain_alert_deliveries (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trigger_id bigint NOT NULL,
    delivered_at bigint NOT NULL,
    success boolean NOT NULL,
    status_code bigint,
    retry_count bigint NOT NULL DEFAULT 0,
    response_snippet text
);
CREATE TABLE app.watch_push_subscriptions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    address text COLLATE "C" NOT NULL,
    endpoint text COLLATE "C" NOT NULL UNIQUE,
    p256dh text NOT NULL,
    auth text NOT NULL,
    user_agent text,
    created_at bigint NOT NULL,
    last_used_at bigint
);

CREATE INDEX idx_rpc_accounts_ss58 ON app.rpc_accounts (ss58);
CREATE INDEX idx_github_accounts_github_user_id ON app.github_accounts (github_user_id);
CREATE INDEX idx_api_keys_account_id ON app.api_keys (account_id) WHERE account_id IS NOT NULL;
CREATE INDEX idx_api_keys_prefix ON app.api_keys (prefix);
CREATE UNIQUE INDEX idx_api_keys_unkey_key_id ON app.api_keys (unkey_key_id) WHERE unkey_key_id IS NOT NULL;
CREATE UNIQUE INDEX idx_api_key_blocks_one_active_per_account ON app.api_key_blocks (account_kind, account_id) WHERE unblocked_at IS NULL;
CREATE INDEX idx_api_key_usage_daily_account_day ON app.api_key_usage_daily (account_kind, account_id, day DESC);
CREATE INDEX idx_api_usage_rollup_batches_expiry ON app.api_usage_rollup_batches (expires_at);
CREATE INDEX idx_api_usage_rollup_day ON app.api_usage_rollup (day DESC, request_count DESC);
CREATE INDEX idx_api_usage_rollup_shape ON app.api_usage_rollup (cost_shape, day DESC);
CREATE INDEX idx_cad_trigger_delivered_at ON app.chain_alert_deliveries (trigger_id, delivered_at DESC);
CREATE INDEX idx_cat_active ON app.chain_alert_triggers (active) WHERE active;
CREATE INDEX idx_cat_owner_ss58_active ON app.chain_alert_triggers (owner_ss58) WHERE owner_ss58 IS NOT NULL AND active;
CREATE INDEX idx_wps_address ON app.watch_push_subscriptions (address, created_at DESC);
