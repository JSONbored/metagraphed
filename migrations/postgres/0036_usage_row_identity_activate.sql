-- Activation phase: apply only after the row-identity import is verified and
-- before native writes start. The migration runner owns one transaction.
-- Newly created sequences disappear with their defaults on transaction rollback.
LOCK TABLE app.api_key_usage_daily, app.api_usage_rollup IN ACCESS EXCLUSIVE MODE;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM app.api_key_usage_daily WHERE source_row_id = 9223372036854775807)
        OR EXISTS (SELECT 1 FROM app.api_usage_rollup WHERE source_row_id = 9223372036854775807) THEN
        RAISE EXCEPTION 'usage source identity has no next bigint value' USING ERRCODE = '22003';
    END IF;
END;
$$;

ALTER TABLE app.api_key_usage_daily
    ALTER COLUMN source_row_id ADD GENERATED BY DEFAULT AS IDENTITY (NO CYCLE);
ALTER TABLE app.api_usage_rollup
    ALTER COLUMN source_row_id ADD GENERATED BY DEFAULT AS IDENTITY (NO CYCLE);

SELECT pg_catalog.setval(
    pg_catalog.pg_get_serial_sequence('app.api_key_usage_daily', 'source_row_id'),
    GREATEST(COALESCE(max(source_row_id), 0), 1),
    COALESCE(max(source_row_id), 0) >= 1
) FROM app.api_key_usage_daily;
SELECT pg_catalog.setval(
    pg_catalog.pg_get_serial_sequence('app.api_usage_rollup', 'source_row_id'),
    GREATEST(COALESCE(max(source_row_id), 0), 1),
    COALESCE(max(source_row_id), 0) >= 1
) FROM app.api_usage_rollup;

-- Sequence gaps from rollback or conflicting inserts are harmless: only the
-- relative order is observable. NO CYCLE makes int64 exhaustion fail instead
-- of wrapping and reusing an old source identity.
CREATE INDEX idx_api_key_usage_source_order
    ON app.api_key_usage_daily (account_id, day DESC, source_row_id);
CREATE INDEX idx_api_usage_rollup_source_order
    ON app.api_usage_rollup (cost_shape, day DESC, source_row_id);
