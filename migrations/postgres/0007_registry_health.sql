-- Load phase for the registry and probe history. Explicit booleans are mapped
-- from SQLite 0/1 through the qualified boolean01 codec.
CREATE SCHEMA IF NOT EXISTS app;

CREATE TABLE app.providers (
    id text COLLATE "C" PRIMARY KEY,
    overlay text NOT NULL,
    source_commit text NOT NULL,
    updated_at bigint NOT NULL DEFAULT floor(extract(epoch FROM statement_timestamp()) * 1000)::bigint
);
CREATE TABLE app.subnets (
    netuid bigint PRIMARY KEY,
    slug text COLLATE "C" NOT NULL UNIQUE,
    name text NOT NULL,
    source text NOT NULL DEFAULT 'community',
    overlay text NOT NULL,
    source_commit text NOT NULL,
    updated_at bigint NOT NULL DEFAULT floor(extract(epoch FROM statement_timestamp()) * 1000)::bigint
);
CREATE TABLE app.surfaces (
    id text COLLATE "C" PRIMARY KEY,
    subnet_netuid bigint NOT NULL,
    provider_id text COLLATE "C",
    surface_key text COLLATE "C" NOT NULL,
    kind text COLLATE "C" NOT NULL,
    url text COLLATE "C" NOT NULL,
    authority text NOT NULL DEFAULT 'community',
    review_state text NOT NULL DEFAULT 'community-submitted',
    probe_eligible boolean NOT NULL DEFAULT false,
    public_safe boolean NOT NULL DEFAULT true,
    overlay text NOT NULL,
    source_commit text NOT NULL,
    updated_at bigint NOT NULL DEFAULT floor(extract(epoch FROM statement_timestamp()) * 1000)::bigint,
    UNIQUE (subnet_netuid, kind, url)
);
CREATE TABLE app.surface_checks (
    surface_id text COLLATE "C" NOT NULL,
    surface_key text COLLATE "C",
    netuid bigint,
    kind text COLLATE "C",
    status text,
    classification text,
    latency_ms bigint,
    status_code bigint,
    ok boolean,
    checked_at bigint NOT NULL,
    PRIMARY KEY (surface_id, checked_at)
);
CREATE TABLE app.surface_failure_daily (
    day text COLLATE "C" NOT NULL,
    netuid bigint,
    kind text COLLATE "C" NOT NULL,
    classification text COLLATE "C" NOT NULL,
    checks bigint NOT NULL,
    updated_at bigint NOT NULL
);
CREATE TABLE app.surface_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    surface_id text COLLATE "C",
    subnet_netuid bigint NOT NULL,
    action text NOT NULL,
    overlay text NOT NULL,
    source_commit text NOT NULL,
    recorded_at bigint NOT NULL DEFAULT floor(extract(epoch FROM statement_timestamp()) * 1000)::bigint
);
CREATE TABLE app.surface_status (
    surface_id text COLLATE "C" PRIMARY KEY,
    surface_key text COLLATE "C",
    netuid bigint,
    kind text,
    url text,
    provider text,
    status text,
    classification text,
    latency_ms bigint,
    status_code bigint,
    last_checked bigint,
    last_ok bigint,
    consecutive_failures bigint NOT NULL DEFAULT 0,
    updated_at bigint
);
CREATE TABLE app.surface_uptime_daily (
    surface_id text COLLATE "C" NOT NULL,
    surface_key text COLLATE "C",
    netuid bigint,
    day text COLLATE "C" NOT NULL,
    samples bigint NOT NULL,
    ok_count bigint NOT NULL,
    uptime_ratio double precision,
    avg_latency_ms bigint,
    status text,
    latency_samples bigint,
    p50_latency_ms bigint,
    p95_latency_ms bigint,
    p99_latency_ms bigint,
    updated_at bigint,
    PRIMARY KEY (surface_id, day)
);
CREATE TABLE app.origin_reachability (
    origin text COLLATE "C" PRIMARY KEY,
    checked_at bigint NOT NULL CHECK (checked_at >= 1000000000000),
    surface_count bigint NOT NULL CHECK (surface_count >= 0),
    samples bigint NOT NULL CHECK (samples >= 0),
    verdict text NOT NULL CHECK (verdict IN ('serving', 'unreachable', 'not-routing', 'indeterminate'))
);
CREATE TABLE app.self_health_checks (
    component text COLLATE "C" NOT NULL,
    checked_at_ms bigint NOT NULL,
    ok boolean NOT NULL,
    http_status bigint,
    latency_ms bigint,
    PRIMARY KEY (component, checked_at_ms)
);
CREATE TABLE app.self_health_daily (
    day text COLLATE "C" NOT NULL,
    component text COLLATE "C" NOT NULL,
    checks bigint NOT NULL,
    ok_count bigint NOT NULL,
    PRIMARY KEY (day, component)
);

CREATE INDEX idx_subnets_source ON app.subnets (source);
CREATE INDEX idx_surfaces_probe ON app.surfaces (probe_eligible, review_state) WHERE probe_eligible;
CREATE INDEX idx_surfaces_provider ON app.surfaces (provider_id);
CREATE INDEX idx_surface_checks_netuid_time ON app.surface_checks (netuid, checked_at DESC);
CREATE INDEX idx_surface_checks_rollup ON app.surface_checks (checked_at DESC, surface_key, netuid, ok, latency_ms, kind, classification);
CREATE INDEX idx_surface_failure_day ON app.surface_failure_daily (day DESC, netuid);
CREATE UNIQUE INDEX idx_surface_failure_key ON app.surface_failure_daily (day, COALESCE(netuid, -1), kind, classification);
CREATE INDEX idx_surface_history_subnet ON app.surface_history (subnet_netuid, recorded_at DESC);
CREATE INDEX idx_surface_history_surface ON app.surface_history (surface_id, recorded_at DESC);
CREATE UNIQUE INDEX idx_surface_status_key ON app.surface_status (surface_key) WHERE surface_key IS NOT NULL;
CREATE INDEX idx_surface_status_netuid ON app.surface_status (netuid);
CREATE INDEX idx_surface_uptime_day ON app.surface_uptime_daily (day);
CREATE UNIQUE INDEX idx_surface_uptime_key_day ON app.surface_uptime_daily (surface_key, day) WHERE surface_key IS NOT NULL;
CREATE INDEX idx_surface_uptime_netuid_day ON app.surface_uptime_daily (netuid, day DESC);
CREATE INDEX idx_origin_reachability_checked_at ON app.origin_reachability (checked_at DESC);
CREATE INDEX idx_origin_reachability_verdict ON app.origin_reachability (verdict, checked_at DESC);

CREATE FUNCTION app.surface_status_lock() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $$
BEGIN
    -- Serialize the alias relation before tuple locks, including the first
    -- observation of an alias that has no row to lock yet.
    PERFORM pg_advisory_xact_lock(1297305, 0);
    RETURN NULL;
END;
$$;

CREATE FUNCTION app.surface_status_alias_insert() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, app AS $$
BEGIN
    IF NEW.surface_key IS NULL OR NEW.surface_key = '' THEN
        RETURN NEW;
    END IF;
    IF EXISTS (
        SELECT 1 FROM app.surface_status newer
        WHERE (newer.surface_key = NEW.surface_key OR
            (newer.surface_id = NEW.surface_id AND newer.surface_key IS DISTINCT FROM NEW.surface_key))
            AND newer.last_checked > NEW.last_checked
    ) THEN
        RETURN NULL;
    END IF;
    UPDATE app.surface_status SET surface_id = 'history:' || surface_key
    WHERE surface_id = NEW.surface_id AND surface_key IS NOT NULL
        AND surface_key IS DISTINCT FROM NEW.surface_key
        AND COALESCE(last_checked, 0) <= NEW.last_checked;
    DELETE FROM app.surface_status
    WHERE surface_id = NEW.surface_id AND surface_key IS NULL
        AND COALESCE(last_checked, 0) <= NEW.last_checked;
    RETURN NEW;
END;
$$;
