-- Load phase for account observations and retained migration bookkeeping.
CREATE SCHEMA IF NOT EXISTS app;

CREATE TABLE app.account_balances (
    ss58 text COLLATE "C" PRIMARY KEY,
    free_tao double precision NOT NULL,
    reserved_tao double precision NOT NULL,
    captured_at bigint NOT NULL
);
CREATE TABLE app.account_balances_passes (
    captured_at bigint PRIMARY KEY,
    expected_rows bigint NOT NULL,
    received_rows bigint NOT NULL DEFAULT 0,
    completed_at bigint,
    scanned bigint,
    outcome text
);
CREATE TABLE app.account_identity (
    account text COLLATE "C" PRIMARY KEY,
    name text,
    url text,
    github text,
    image text,
    discord text,
    description text,
    additional text,
    captured_at bigint NOT NULL
);
CREATE TABLE app.account_identity_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account text COLLATE "C" NOT NULL,
    observed_at bigint NOT NULL,
    name text,
    url text,
    github text,
    image text,
    discord text,
    description text,
    additional text,
    identity_hash text NOT NULL,
    UNIQUE (account, observed_at)
);
CREATE TABLE app.hotkey_alpha (
    hotkey text COLLATE "C" NOT NULL,
    netuid bigint NOT NULL,
    total_alpha double precision NOT NULL,
    captured_at bigint NOT NULL,
    PRIMARY KEY (hotkey, netuid)
);
CREATE TABLE app.hotkey_alpha_passes (
    captured_at bigint PRIMARY KEY,
    expected_rows bigint NOT NULL,
    received_rows bigint NOT NULL DEFAULT 0,
    completed_at bigint
);
CREATE TABLE app.nominator_positions (
    coldkey text COLLATE "C" NOT NULL,
    hotkey text COLLATE "C" NOT NULL,
    netuid bigint NOT NULL,
    share_fraction double precision,
    captured_at bigint NOT NULL,
    shares text,
    source text COLLATE "C" NOT NULL DEFAULT 'alpha',
    PRIMARY KEY (coldkey, hotkey, netuid)
);
CREATE TABLE app.nominator_positions_passes (
    captured_at bigint PRIMARY KEY,
    expected_rows bigint NOT NULL,
    received_rows bigint NOT NULL DEFAULT 0,
    completed_at bigint
);
CREATE TABLE app.nominator_scan_receipts (
    captured_at bigint NOT NULL,
    coldkey text COLLATE "C" NOT NULL,
    row_count bigint NOT NULL CHECK (row_count > 0),
    PRIMARY KEY (captured_at, coldkey)
);
CREATE TABLE app.validator_nominator_counts (
    hotkey text COLLATE "C" PRIMARY KEY,
    nominator_count bigint NOT NULL,
    captured_at bigint NOT NULL
);
CREATE TABLE app.validator_nominator_counts_passes (
    captured_at bigint PRIMARY KEY,
    expected_rows bigint NOT NULL,
    received_rows bigint NOT NULL DEFAULT 0,
    completed_at bigint
);
CREATE TABLE app._migration_capture_governance (
    table_name text COLLATE "C" NOT NULL,
    row_key text COLLATE "C" NOT NULL,
    payload text NOT NULL,
    PRIMARY KEY (table_name, row_key)
);
CREATE TABLE app._migration_capture_governance_phase (
    id bigint PRIMARY KEY,
    status text NOT NULL
);
CREATE TABLE app._migration_user_state (
    table_name text COLLATE "C" NOT NULL,
    row_key text COLLATE "C" NOT NULL,
    payload text NOT NULL,
    PRIMARY KEY (table_name, row_key)
);
CREATE TABLE app._migration_user_state_phase (
    id bigint PRIMARY KEY,
    status text NOT NULL
);

CREATE INDEX idx_account_balances_passes_completed ON app.account_balances_passes (completed_at DESC);
CREATE INDEX idx_account_identity_history_account_observed ON app.account_identity_history (account, observed_at DESC, id DESC);
CREATE INDEX idx_hotkey_alpha_captured ON app.hotkey_alpha (captured_at);
CREATE INDEX idx_hotkey_alpha_netuid ON app.hotkey_alpha (netuid, total_alpha DESC);
CREATE INDEX idx_hotkey_alpha_passes_completed ON app.hotkey_alpha_passes (completed_at DESC);
CREATE INDEX idx_nominator_positions_capture_pool ON app.nominator_positions (captured_at, hotkey, netuid);
CREATE INDEX idx_nominator_positions_hotkey ON app.nominator_positions (hotkey, netuid);
CREATE INDEX nominator_positions_coldkey_source_captured_idx ON app.nominator_positions (coldkey, source, captured_at);
CREATE INDEX idx_nominator_positions_passes_completed ON app.nominator_positions_passes (completed_at DESC);
CREATE INDEX idx_validator_nominator_counts_passes_completed ON app.validator_nominator_counts_passes (completed_at DESC);
